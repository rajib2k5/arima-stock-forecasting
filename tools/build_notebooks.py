"""Build the notebooks. This file is the single source of truth for every notebook.

Run:    uv run python tools/build_notebooks.py          # write notebooks/*.ipynb
        uv run python tools/build_notebooks.py --check  # exit 1 if any notebook is stale

Why a builder instead of editing notebooks by hand: a .ipynb file is JSON full of noise
(random cell ids, execution counts, saved outputs). Generated from here, the file is the same
bytes every time, so a git diff shows only real changes, and a test can confirm the committed
notebook still matches this file.

Notebooks import from `arima_forecasting`; they never copy source code.
"""

