NOTEBOOKS: dict[str, Callable[[], list[Cell]]] = {
    "00_project_tour.ipynb": tour_cells,
    "01_data_and_eda.ipynb": data_eda_cells,
    "02_stationarity_and_identification.ipynb": order_selection_cells,
}


def build_notebook(cells: Sequence[Cell]) -> nbformat.NotebookNode:
    nb_cells = []
    for index, (kind, source) in enumerate(cells):
        # nbformat 4.5+ gives every cell a random id. We set our own so the file is identical
        # on every build.
        cell_id = f"cell-{index:02d}"
        if kind == "markdown":
            nb_cells.append(new_markdown_cell(source, id=cell_id))
        elif kind == "code":
            # new_code_cell already means no outputs and execution_count None.
            nb_cells.append(new_code_cell(source, id=cell_id))
        else:
            raise ValueError(f"unknown cell kind {kind!r}")
    return new_notebook(cells=nb_cells, metadata=METADATA)


def render(cells: Sequence[Cell]) -> str:
    """The exact text of a notebook file, with a trailing newline."""
    notebook = build_notebook(cells)
    nbformat.validate(notebook)
    text = nbformat.writes(notebook)
    return text if text.endswith("\n") else text + "\n"


def render_all() -> dict[str, str]:
    """File name -> file text for every notebook, built in memory."""
    return {name: render(make_cells()) for name, make_cells in NOTEBOOKS.items()}


def stale_notebooks(notebook_dir: Path) -> list[str]:
    """Describe every notebook in `notebook_dir` that is missing or differs from the build."""
    problems = []
    for name, text in render_all().items():
        path = notebook_dir / name
        if not path.exists():
            problems.append(f"missing: {path}")
        elif path.read_text(encoding="utf-8") != text:
            problems.append(f"stale:   {path}")
    return problems


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build the notebooks from this file.")
    parser.add_argument(
        "--check",
        action="store_true",
        help="write nothing; exit 1 and list the notebooks that are stale or missing",
    )
    parser.add_argument(
        "--notebooks-dir",
        type=Path,
        default=NOTEBOOK_DIR,
        help="folder for the .ipynb files (default: notebooks/ in this repo)",
    )
    args = parser.parse_args(argv)

    if args.check:
        problems = stale_notebooks(args.notebooks_dir)
        for problem in problems:
            print(problem)
        if problems:
            print("run: uv run python tools/build_notebooks.py")
            return 1
        print("notebooks are in sync")
        return 0

    args.notebooks_dir.mkdir(parents=True, exist_ok=True)
    for name, text in render_all().items():
        path = args.notebooks_dir / name
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path}")
    return 0


